CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================================================
-- 1. DIVISIONS
-- =========================================================

CREATE TABLE public.divisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 2. PROFILES
-- Identitas pengguna yang terhubung dengan Supabase Auth.
-- Role peserta selalu menjadi default.
-- =========================================================

CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'PESERTA'
        CHECK (role IN ('PIC', 'PESERTA')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 3. DIVISION PIC ASSIGNMENTS
-- Satu PIC aktif hanya mengelola satu divisi.
-- Satu divisi hanya memiliki satu PIC aktif.
-- =========================================================

CREATE TABLE public.division_pic_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    pic_user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at TIMESTAMPTZ,

    CHECK (ended_at IS NULL OR ended_at > assigned_at)
);

CREATE UNIQUE INDEX one_active_pic_per_division
ON public.division_pic_assignments(division_id)
WHERE ended_at IS NULL;

CREATE UNIQUE INDEX one_active_division_per_pic
ON public.division_pic_assignments(pic_user_id)
WHERE ended_at IS NULL;

-- =========================================================
-- 4. PARTICIPANT DIVISION HISTORY
-- Menyimpan riwayat perpindahan divisi peserta.
-- =========================================================

CREATE TABLE public.participant_divisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at TIMESTAMPTZ,

    CHECK (ended_at IS NULL OR ended_at > started_at),

    UNIQUE (id, division_id, user_id)
);

CREATE UNIQUE INDEX one_active_division_per_participant
ON public.participant_divisions(user_id)
WHERE ended_at IS NULL;

-- =========================================================
-- 5. GROUPS
-- =========================================================

CREATE TABLE public.groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    archived_at TIMESTAMPTZ,

    UNIQUE (division_id, name),
    UNIQUE (id, division_id)
);

-- =========================================================
-- 6. GROUP MEMBERS
-- Menyimpan riwayat keanggotaan dan ketua kelompok.
-- Ketua ditetapkan PIC berdasarkan kesepakatan anggota.
-- =========================================================

CREATE TABLE public.group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    division_id BIGINT NOT NULL,
    participant_division_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    is_leader BOOLEAN NOT NULL DEFAULT FALSE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    left_at TIMESTAMPTZ,

    CHECK (left_at IS NULL OR left_at > joined_at),

    FOREIGN KEY (group_id, division_id)
        REFERENCES public.groups(id, division_id)
        ON DELETE RESTRICT,

    FOREIGN KEY (participant_division_id, division_id, user_id)
        REFERENCES public.participant_divisions(id, division_id, user_id)
        ON DELETE RESTRICT
);

CREATE UNIQUE INDEX one_active_group_per_participant
ON public.group_members(user_id)
WHERE left_at IS NULL;

CREATE UNIQUE INDEX one_active_leader_per_group
ON public.group_members(group_id)
WHERE is_leader = TRUE AND left_at IS NULL;

CREATE INDEX group_members_group_idx
ON public.group_members(group_id);

CREATE INDEX group_members_user_idx
ON public.group_members(user_id);

-- =========================================================
-- 7. ASSIGNMENTS
-- Deadline maksimal tujuh hari setelah tugas dibuat.
-- Waktu deadline disimpan sebagai TIMESTAMPTZ.
-- =========================================================

CREATE TABLE public.assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    created_by UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    title VARCHAR(255) NOT NULL,
    module VARCHAR(100) NOT NULL,
    description TEXT,
    deadline TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (deadline > created_at),
    CHECK (deadline <= created_at + INTERVAL '7 days'),

    UNIQUE (id, division_id)
);

CREATE INDEX assignments_division_deadline_idx
ON public.assignments(division_id, deadline);

-- =========================================================
-- 8. SUBMISSIONS
-- Satu kelompok memiliki satu data pengumpulan per tugas.
-- Revisi memperbarui file terbaru tanpa menghapus riwayat.
-- =========================================================

CREATE TABLE public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    division_id BIGINT NOT NULL,
    submitted_by UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL
        CHECK (status IN ('submitted', 'late')),

    file_path TEXT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 52428800),
    file_type VARCHAR(150) NOT NULL,

    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    FOREIGN KEY (assignment_id, division_id)
        REFERENCES public.assignments(id, division_id)
        ON DELETE RESTRICT,

    FOREIGN KEY (group_id, division_id)
        REFERENCES public.groups(id, division_id)
        ON DELETE RESTRICT,

    UNIQUE (assignment_id, group_id)
);

CREATE INDEX submissions_group_idx
ON public.submissions(group_id);

CREATE INDEX submissions_assignment_idx
ON public.submissions(assignment_id);

-- =========================================================
-- 9. SUBMISSION REVISIONS
-- Riwayat setiap perubahan file pengumpulan.
-- =========================================================

CREATE TABLE public.submission_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL
        REFERENCES public.submissions(id) ON DELETE RESTRICT,
    revision_number INTEGER NOT NULL CHECK (revision_number > 0),
    uploaded_by UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    file_path TEXT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 52428800),
    file_type VARCHAR(150) NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (submission_id, revision_number)
);

-- =========================================================
-- 10. SUBMISSION MEMBERS
-- Anggota yang benar-benar berkontribusi pada tugas.
-- Nama disimpan sebagai snapshot riwayat.
-- =========================================================

CREATE TABLE public.submission_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL
        REFERENCES public.submissions(id) ON DELETE RESTRICT,
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    full_name_snapshot VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (submission_id, user_id)
);

-- =========================================================
-- 11. DIVISION TRANSFER REQUESTS
-- PIC asal mengajukan, PIC tujuan menyetujui/menolak.
-- =========================================================

CREATE TABLE public.division_transfer_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    from_division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    to_division_id BIGINT NOT NULL
        REFERENCES public.divisions(id) ON DELETE RESTRICT,
    requested_by_pic_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,
    reviewed_by_pic_id UUID
        REFERENCES public.profiles(id) ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),

    request_note TEXT,
    review_note TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,

    CHECK (from_division_id <> to_division_id),

    CHECK (
        (status = 'PENDING' AND reviewed_at IS NULL)
        OR
        (status IN ('APPROVED', 'REJECTED') AND reviewed_at IS NOT NULL)
    )
);

CREATE INDEX transfer_requests_participant_idx
ON public.division_transfer_requests(participant_user_id);

CREATE INDEX transfer_requests_status_idx
ON public.division_transfer_requests(status);

-- =========================================================
-- 12. AUTOMATIC PROFILE CREATION
-- Akun baru tidak boleh menentukan role sendiri.
-- Role default selalu PESERTA.
-- PIC ditetapkan melalui proses administrasi terpisah.
-- =========================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role)
    VALUES (
        NEW.id,
        COALESCE(
            NULLIF(TRIM(NEW.raw_user_meta_data ->> 'full_name'), ''),
            NULLIF(TRIM(NEW.raw_user_meta_data ->> 'name'), ''),
            SPLIT_PART(NEW.email, '@', 1)
        ),
        'PESERTA'
    )
    ON CONFLICT (id) DO NOTHING;

    RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();

-- =========================================================
-- 13. UPDATED_AT TRIGGER
-- =========================================================

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER profiles_updated_at
BEFORE UPDATE ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER assignments_updated_at
BEFORE UPDATE ON public.assignments
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER submissions_updated_at
BEFORE UPDATE ON public.submissions
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

